#!/usr/bin/env python3
"""Generates src/tz/windows_zones_generated.mbt from CLDR's windowsZones.xml.

Usage:
    python3 scripts/gen_windows_zones.py --source <windowsZones.xml> \
        --release <CLDR release> --output <path>

The source is common/supplemental/windowsZones.xml from a Unicode CLDR
release. Only the territory "001" entry of each Windows zone is kept, since
the region of the host is unknown; it is the primary IANA zone of that
Windows zone. The release recorded in the generated file's header is the
value of --release.
"""

import argparse
import sys
import xml.etree.ElementTree as ET

PRIMARY_TERRITORY = "001"


def collect(source):
    """Returns {windows zone key name: IANA zone name}."""
    names = {}
    for zone in ET.parse(source).getroot().iter("mapZone"):
        if zone.get("territory") != PRIMARY_TERRITORY:
            continue
        other = zone.get("other")
        iana = zone.get("type")
        if not other or not iana or " " in iana:
            raise ValueError("unexpected mapZone entry: %r" % (zone.attrib,))
        if other in names:
            raise ValueError("duplicate territory %s entry for %r" % (PRIMARY_TERRITORY, other))
        names[other] = iana
    return names


def mbt_string_literal(s):
    escaped = s.replace("\\", "\\\\").replace('"', '\\"')
    return '"%s"' % escaped


def generate(names, release):
    out = []
    out.append("///|")
    out.append(
        "// Generated by scripts/gen_windows_zones.py from CLDR windowsZones.xml."
    )
    out.append("// Source release: %s" % release)
    out.append("// Do not edit by hand; re-run the script to regenerate.")
    out.append("")
    out.append("///|")
    out.append(
        "let windows_zone_iana_names : Map[String, String] = Map::from_array(["
    )
    for key in sorted(names):
        out.append(
            "  (%s, %s)," % (mbt_string_literal(key), mbt_string_literal(names[key]))
        )
    out.append("])")
    out.append("")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True)
    parser.add_argument("--release", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    names = collect(args.source)
    if not names:
        print(f"no territory {PRIMARY_TERRITORY} entries in {args.source}", file=sys.stderr)
        sys.exit(1)
    with open(args.output, "w") as f:
        f.write(generate(names, args.release))
    print(f"wrote {args.output}: {len(names)} Windows zones")


if __name__ == "__main__":
    main()
